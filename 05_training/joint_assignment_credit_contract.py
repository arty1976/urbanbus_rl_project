"""H4M-AE-R9.8 LS3-CR0/CR1 joint-assignment credit contract and rollout buffer.

Reward V2 is not touched.  This is a new attribution layer *over* frozen Reward
V2 outputs: it decides which already-computed rewards belong to which assignment
decision, and nothing about how those rewards are computed.

Team reward
-----------
    team_reward_t = mean( RewardV2_t(agent_i) for active agent_i )

Arithmetic mean over *active* agents only, so the scale does not drift with fleet
size and idle vehicles do not dilute the signal.  An assignment transition with
zero active agents is an error, not a zero: the contract fails closed rather than
quietly inventing a reward.

Assignment interval
-------------------
Assignment decisions are coarser than operational transitions, so credit runs
over the half-open interval between consecutive decisions:

    R_assign_k     = sum_j gamma^j * team_reward_(T_k + j)
    Gamma_assign_k = gamma ^ delta_operational_steps_k

This is a semi-Markov high-level decision process.  Where the runtime happens to
take exactly one operational step per assignment, delta is 1 and the whole thing
collapses to ordinary PPO credit -- no cadence is changed to make that true.

Frozen action support
---------------------
PPO's ratio is only meaningful if the behaviour policy and the update policy saw
the same action set.  The safe set is therefore *rollout evidence*: it is stored
with the transition and replayed, never regenerated by re-running Local Search or
Zero-Loss.  Regeneration could change the candidate count, the mask, or the
denominator, and would silently invalidate every ratio computed from it.

Forced rows
-----------
When only NO_ASSIGN is legal there is no choice to learn from: log-prob is
identically 0 and the policy gradient is structurally zero.  Those rows carry
`forced_action = True`, contribute nothing to actor or entropy loss, and are
excluded from the actor denominator -- but they still carry reward, return and
value, because the state is still informative for the critic.
"""

